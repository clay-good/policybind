/**
 * Register completion provider
 */
function registerCompletionProvider(context: vscode.ExtensionContext) {
    const completionProvider = vscode.languages.registerCompletionItemProvider(
        [{ scheme: 'file', pattern: '**/*.policy.{yaml,yml}' }, 'yaml'],
        {
            provideCompletionItems(document, position) {
                const lineText = document.lineAt(position).text;
                const linePrefix = lineText.substring(0, position.character);

                const completions: vscode.CompletionItem[] = [];

                // Action values
                if (linePrefix.match(/action:\s*$/)) {
                    const actions = ['ALLOW', 'DENY', 'MODIFY', 'REQUIRE_APPROVAL', 'RATE_LIMIT', 'AUDIT', 'REDIRECT'];
                    actions.forEach(action => {
                        const item = new vscode.CompletionItem(action, vscode.CompletionItemKind.EnumMember);
                        item.detail = `PolicyBind action: ${action}`;
                        completions.push(item);
                    });
                }

                // Provider values
                if (linePrefix.match(/provider:\s*$/)) {
                    const providers = ['openai', 'anthropic', 'google', 'azure', 'aws', 'cohere', 'mistral', 'ollama', 'huggingface'];
                    providers.forEach(provider => {
                        const item = new vscode.CompletionItem(provider, vscode.CompletionItemKind.Value);
                        item.detail = `AI Provider: ${provider}`;
                        completions.push(item);
                    });
                }

                // Data classification values
                if (linePrefix.match(/data_classification:\s*$/)) {
                    const classifications = ['public', 'internal', 'confidential', 'restricted', 'pii', 'phi', 'financial'];
                    classifications.forEach(cls => {
                        const item = new vscode.CompletionItem(cls, vscode.CompletionItemKind.Value);
                        item.detail = `Data classification: ${cls}`;
                        completions.push(item);
                    });
                }

                // Match condition keys
                if (linePrefix.match(/match_conditions:\s*$/) || linePrefix.match(/^\s+-?\s*$/)) {
                    const conditions = [
                        { name: 'provider', desc: 'Match by AI provider' },
                        { name: 'model', desc: 'Match by model name' },
                        { name: 'department', desc: 'Match by user department' },
                        { name: 'user_id', desc: 'Match by user identifier' },
                        { name: 'data_classification', desc: 'Match by data classification' },
                        { name: 'source_application', desc: 'Match by application' },
                        { name: 'estimated_cost', desc: 'Match by estimated cost' },
                        { name: 'estimated_tokens', desc: 'Match by token count' },
                        { name: 'and', desc: 'All conditions must match' },
                        { name: 'or', desc: 'Any condition must match' },
                        { name: 'not', desc: 'Negate a condition' },
                    ];
                    conditions.forEach(cond => {
                        const item = new vscode.CompletionItem(cond.name, vscode.CompletionItemKind.Field);
                        item.detail = cond.desc;
                        item.insertText = new vscode.SnippetString(`${cond.name}: `);
                        completions.push(item);
                    });
                }

                // Operators
                if (linePrefix.match(/^\s+\w+:\s*$/)) {
                    const operators = [
                        { name: 'eq', desc: 'Equals' },
                        { name: 'ne', desc: 'Not equals' },
                        { name: 'gt', desc: 'Greater than' },
                        { name: 'gte', desc: 'Greater than or equal' },
                        { name: 'lt', desc: 'Less than' },
                        { name: 'lte', desc: 'Less than or equal' },
                        { name: 'in', desc: 'Value in list' },
                        { name: 'not_in', desc: 'Value not in list' },
                        { name: 'contains', desc: 'Contains substring/element' },
                        { name: 'not_contains', desc: 'Does not contain' },
                        { name: 'matches', desc: 'Regex match' },
                    ];
                    operators.forEach(op => {
                        const item = new vscode.CompletionItem(op.name, vscode.CompletionItemKind.Operator);
                        item.detail = op.desc;
                        item.insertText = new vscode.SnippetString(`\n    ${op.name}: `);
                        completions.push(item);
                    });
                }

                return completions;
            }
        },
        ':', ' '
    );

    context.subscriptions.push(completionProvider);
}

/**
 * Register document validation
 */
function registerValidation(context: vscode.ExtensionContext) {
    // Validate on open
    vscode.workspace.onDidOpenTextDocument((document) => {
        if (isPolicyFile(document)) {
            validateDocument(document);
        }
    }, null, context.subscriptions);

    // Validate on save
    vscode.workspace.onDidSaveTextDocument((document) => {
        const config = vscode.workspace.getConfiguration('policybind');
        if (config.get('validation.onSave') && isPolicyFile(document)) {
            validateDocument(document);
        }
    }, null, context.subscriptions);

    // Validate on change (debounced)
    let validationTimeout: NodeJS.Timeout | undefined;
    vscode.workspace.onDidChangeTextDocument((event) => {
        const config = vscode.workspace.getConfiguration('policybind');
        if (config.get('validation.onType') && isPolicyFile(event.document)) {
            if (validationTimeout) {
                clearTimeout(validationTimeout);
            }
            validationTimeout = setTimeout(() => {
                validateDocument(event.document);
            }, 500);
        }
    }, null, context.subscriptions);

    // Clear diagnostics when document closes
    vscode.workspace.onDidCloseTextDocument((document) => {
        diagnosticCollection.delete(document.uri);
    }, null, context.subscriptions);
}

/**
 * Check if document is a policy file
 */
function isPolicyFile(document: vscode.TextDocument): boolean {
    const config = vscode.workspace.getConfiguration('policybind');
    const patterns = config.get<string[]>('filePatterns') || [];

    const relativePath = vscode.workspace.asRelativePath(document.uri);

    for (const pattern of patterns) {
        const regex = new RegExp(
            pattern
                .replace(/\*\*/g, '.*')
                .replace(/\*/g, '[^/]*')
                .replace(/\./g, '\\.')
        );
        if (regex.test(relativePath)) {
            return true;
        }
    }

    return false;
}

/**
 * Validate a policy document
 */
function validateDocument(document: vscode.TextDocument): number {
    const config = vscode.workspace.getConfiguration('policybind');
    if (!config.get('validation.enabled')) {
        return 0;
    }

    const diagnostics: vscode.Diagnostic[] = [];
    const text = document.getText();

    try {
        // Parse YAML
        const policy = yaml.load(text) as Record<string, unknown>;

        if (!policy) {
            diagnostics.push(
                new vscode.Diagnostic(
                    new vscode.Range(0, 0, 0, 0),
                    'Empty policy file',
                    vscode.DiagnosticSeverity.Warning
                )
            );
        } else {
            // Validate structure
            validatePolicyStructure(policy, document, diagnostics);
        }
    } catch (error) {
        if (error instanceof yaml.YAMLException) {
            const line = error.mark?.line || 0;
            const col = error.mark?.column || 0;
            diagnostics.push(
                new vscode.Diagnostic(
                    new vscode.Range(line, col, line, col + 10),
                    `YAML syntax error: ${error.message}`,
                    vscode.DiagnosticSeverity.Error
                )
            );
        }
    }

    diagnosticCollection.set(document.uri, diagnostics);
    return diagnostics.filter(d => d.severity === vscode.DiagnosticSeverity.Error).length;
}

/**
 * Validate policy structure
 */
function validatePolicyStructure(
    policy: Record<string, unknown>,
    document: vscode.TextDocument,
    diagnostics: vscode.Diagnostic[]
) {
    // Check required fields
    if (!policy.name) {
        addDiagnostic(document, diagnostics, 'name', 'Missing required field: name', vscode.DiagnosticSeverity.Error);
    }

    if (!policy.version) {
        addDiagnostic(document, diagnostics, 'version', 'Missing required field: version', vscode.DiagnosticSeverity.Error);
    }

    if (!policy.rules) {
        addDiagnostic(document, diagnostics, 'rules', 'Missing required field: rules', vscode.DiagnosticSeverity.Error);
    } else if (!Array.isArray(policy.rules)) {
        addDiagnostic(document, diagnostics, 'rules', 'rules must be an array', vscode.DiagnosticSeverity.Error);
    } else {
        // Validate each rule
        const ruleNames = new Set<string>();
        (policy.rules as Record<string, unknown>[]).forEach((rule, index) => {
            validateRule(rule, index, document, diagnostics, ruleNames);
        });
    }

    // Validate version format
    if (policy.version && typeof policy.version === 'string') {
        if (!/^\d+\.\d+\.\d+(-[a-zA-Z0-9.-]+)?$/.test(policy.version)) {
            addDiagnostic(
                document,
                diagnostics,
                'version',
                'version should follow semantic versioning (e.g., 1.0.0)',
                vscode.DiagnosticSeverity.Warning
            );
        }
    }
}

/**
 * Validate a single rule
 */
function validateRule(
    rule: Record<string, unknown>,
    index: number,
    document: vscode.TextDocument,
    diagnostics: vscode.Diagnostic[],
    ruleNames: Set<string>
) {
    const rulePrefix = `rules[${index}]`;

    // Check required fields
    if (!rule.name) {
        addDiagnostic(document, diagnostics, rulePrefix, 'Rule missing required field: name', vscode.DiagnosticSeverity.Error);
    } else {
        // Check for duplicate names
        if (ruleNames.has(rule.name as string)) {
            addDiagnostic(document, diagnostics, rule.name as string, `Duplicate rule name: ${rule.name}`, vscode.DiagnosticSeverity.Error);
        }
        ruleNames.add(rule.name as string);
    }

    if (!rule.action) {
        addDiagnostic(document, diagnostics, rulePrefix, 'Rule missing required field: action', vscode.DiagnosticSeverity.Error);
    } else {
        // Validate action value
        const validActions = ['ALLOW', 'DENY', 'MODIFY', 'REQUIRE_APPROVAL', 'RATE_LIMIT', 'AUDIT', 'REDIRECT'];
        if (!validActions.includes(rule.action as string)) {
            addDiagnostic(
                document,
                diagnostics,
                rule.action as string,
                `Invalid action: ${rule.action}. Must be one of: ${validActions.join(', ')}`,
                vscode.DiagnosticSeverity.Error
            );
        }
    }

    // Validate priority range
    if (rule.priority !== undefined) {
        const priority = rule.priority as number;
        if (priority < -1000 || priority > 1000) {
            addDiagnostic(
                document,
                diagnostics,
                'priority',
                'priority should be between -1000 and 1000',
                vscode.DiagnosticSeverity.Warning
            );
        }
    }

    // Warn if action is DENY but no reason provided
    if (rule.action === 'DENY') {
        const params = rule.action_params as Record<string, unknown> | undefined;
        if (!params?.reason) {
            addDiagnostic(
                document,
                diagnostics,
                rule.name as string || rulePrefix,
                'DENY action should include a reason in action_params',
                vscode.DiagnosticSeverity.Warning
            );
        }
    }
}

/**
 * Add a diagnostic at the location of a keyword
 */
function addDiagnostic(
    document: vscode.TextDocument,
    diagnostics: vscode.Diagnostic[],
    searchText: string,
    message: string,
    severity: vscode.DiagnosticSeverity
) {
    const text = document.getText();
    const index = text.indexOf(searchText);

    let range: vscode.Range;
    if (index >= 0) {
        const position = document.positionAt(index);
        range = new vscode.Range(position, position.translate(0, searchText.length));
    } else {
        range = new vscode.Range(0, 0, 0, 0);
    }

    const diagnostic = new vscode.Diagnostic(range, message, severity);
    diagnostic.source = 'PolicyBind';
    diagnostics.push(diagnostic);
}

/**
 * Register code actions
 */
function registerCodeActions(context: vscode.ExtensionContext) {
    const codeActionProvider = vscode.languages.registerCodeActionsProvider(
        [{ scheme: 'file', pattern: '**/*.policy.{yaml,yml}' }],
        {
            provideCodeActions(document, range, context) {
                const actions: vscode.CodeAction[] = [];

                // Provide quick fixes for diagnostics
                for (const diagnostic of context.diagnostics) {
                    if (diagnostic.message.includes('DENY action should include a reason')) {
                        const fix = new vscode.CodeAction(
                            'Add reason to action_params',
                            vscode.CodeActionKind.QuickFix
                        );
                        fix.diagnostics = [diagnostic];
                        fix.edit = new vscode.WorkspaceEdit();
                        // This is a simplified fix - a real implementation would be more sophisticated
                        actions.push(fix);
                    }
                }

                return actions;
            }
        }
    );

    context.subscriptions.push(codeActionProvider);
}

/**
 * Deactivate the extension
 */
export function deactivate() {
    if (diagnosticCollection) {
        diagnosticCollection.dispose();
    }
}
