/**
 * PolicyBind VS Code Extension
 *
 * Provides language support, validation, and IntelliSense for
 * PolicyBind AI governance policy files.
 */

import * as vscode from 'vscode';
import * as yaml from 'js-yaml';
import Ajv from 'ajv';
import * as path from 'path';
import * as fs from 'fs';

// Schema for validation
let policySchema: object | null = null;
let ajv: Ajv | null = null;

// Diagnostic collection for validation errors
let diagnosticCollection: vscode.DiagnosticCollection;

/**
 * Activate the extension
 */
export function activate(context: vscode.ExtensionContext) {
    console.log('PolicyBind extension is now active');

    // Initialize diagnostic collection
    diagnosticCollection = vscode.languages.createDiagnosticCollection('policybind');
    context.subscriptions.push(diagnosticCollection);

    // Load the JSON schema
    loadSchema(context);

    // Register commands
    registerCommands(context);

    // Register hover provider
    registerHoverProvider(context);

    // Register completion provider
    registerCompletionProvider(context);

    // Register document validation
    registerValidation(context);

    // Register code actions
    registerCodeActions(context);
}

/**
 * Load the policy JSON schema
 */
function loadSchema(context: vscode.ExtensionContext) {
    try {
        const schemaPath = path.join(
            context.extensionPath,
            'schemas',
            'policybind-policy.schema.json'
        );
        const schemaContent = fs.readFileSync(schemaPath, 'utf8');
        policySchema = JSON.parse(schemaContent);

        ajv = new Ajv({ allErrors: true, verbose: true });
        ajv.compile(policySchema);
    } catch (error) {
        console.error('Failed to load PolicyBind schema:', error);
    }
}

/**
 * Register extension commands
 */
function registerCommands(context: vscode.ExtensionContext) {
    // Validate current file
    context.subscriptions.push(
        vscode.commands.registerCommand('policybind.validateFile', () => {
            const editor = vscode.window.activeTextEditor;
            if (editor) {
                validateDocument(editor.document);
                vscode.window.showInformationMessage('PolicyBind: Validation complete');
            }
        })
    );

    // Validate all policies in workspace
    context.subscriptions.push(
        vscode.commands.registerCommand('policybind.validateWorkspace', async () => {
            const files = await vscode.workspace.findFiles(
                '**/*.policy.{yaml,yml}',
                '**/node_modules/**'
            );

            let errorCount = 0;
            for (const file of files) {
                const document = await vscode.workspace.openTextDocument(file);
                const errors = validateDocument(document);
                errorCount += errors;
            }

            vscode.window.showInformationMessage(
                `PolicyBind: Validated ${files.length} files, ${errorCount} errors found`
            );
        })
    );

    // Create new policy set
    context.subscriptions.push(
        vscode.commands.registerCommand('policybind.createPolicySet', async (uri: vscode.Uri) => {
            const name = await vscode.window.showInputBox({
                prompt: 'Enter policy set name',
                placeHolder: 'my-policy-set',
                validateInput: (value) => {
                    if (!/^[a-z0-9][a-z0-9-]*[a-z0-9]$/.test(value)) {
                        return 'Name must be lowercase alphanumeric with hyphens';
                    }
                    return null;
                }
            });

            if (!name) return;

            const template = `# PolicyBind Policy Set
# Generated by PolicyBind VS Code Extension

name: ${name}
version: 1.0.0
description: |
  Description of this policy set.
  Add details about its purpose and scope.

metadata:
  author: your-team
  environment: development
  # compliance:
  #   - SOC2
  #   - GDPR

rules:
  # Example: Allow all requests by default (low priority catch-all)
  - name: allow-all-default
    description: Default allow rule for all requests
    priority: 0
    enabled: true
    match_conditions: {}
    action: ALLOW

  # Example: Deny PII data to external providers
  # - name: deny-pii-external
  #   description: Block PII data from going to external AI providers
  #   priority: 100
  #   enabled: true
  #   match_conditions:
  #     data_classification:
  #       contains: pii
  #   action: DENY
  #   action_params:
  #     reason: PII data cannot be sent to external AI providers
`;

            const folderPath = uri?.fsPath || vscode.workspace.workspaceFolders?.[0]?.uri.fsPath;
            if (!folderPath) {
                vscode.window.showErrorMessage('No folder selected');
                return;
            }

            const filePath = path.join(folderPath, `${name}.policy.yaml`);
            fs.writeFileSync(filePath, template);

            const document = await vscode.workspace.openTextDocument(filePath);
            await vscode.window.showTextDocument(document);
        })
    );

    // Create new rule
    context.subscriptions.push(
        vscode.commands.registerCommand('policybind.createRule', async () => {
            const editor = vscode.window.activeTextEditor;
            if (!editor) {
                vscode.window.showErrorMessage('No active editor');
                return;
            }

            const name = await vscode.window.showInputBox({
                prompt: 'Enter rule name',
                placeHolder: 'my-rule-name'
            });

            if (!name) return;

            const action = await vscode.window.showQuickPick(
                ['ALLOW', 'DENY', 'MODIFY', 'REQUIRE_APPROVAL', 'RATE_LIMIT', 'AUDIT'],
                { placeHolder: 'Select action' }
            );

            if (!action) return;

            const ruleTemplate = `
  - name: ${name}
    description: Description of this rule
    priority: 100
    enabled: true
    match_conditions:
      # Add your conditions here
      provider: openai
    action: ${action}
    action_params:
      reason: Reason for this action
`;

            // Insert at cursor position
            editor.edit((editBuilder) => {
                editBuilder.insert(editor.selection.active, ruleTemplate);
            });
        })
    );

    // Format document
    context.subscriptions.push(
        vscode.commands.registerCommand('policybind.formatDocument', () => {
            const editor = vscode.window.activeTextEditor;
            if (editor) {
                vscode.commands.executeCommand('editor.action.formatDocument');
            }
        })
    );

    // Show documentation
    context.subscriptions.push(
        vscode.commands.registerCommand('policybind.showDocumentation', () => {
            vscode.env.openExternal(
                vscode.Uri.parse('https://policybind.io/docs')
            );
        })
    );
}

/**
 * Register hover provider for policy keywords
 */
function registerHoverProvider(context: vscode.ExtensionContext) {
    const hoverProvider = vscode.languages.registerHoverProvider(
        [{ scheme: 'file', pattern: '**/*.policy.{yaml,yml}' }, 'yaml'],
        {
            provideHover(document, position) {
                const wordRange = document.getWordRangeAtPosition(position, /[\w-]+/);
                if (!wordRange) return null;

                const word = document.getText(wordRange);
                const hoverContent = getHoverContent(word);

                if (hoverContent) {
                    return new vscode.Hover(hoverContent);
                }
                return null;
            }
        }
    );

    context.subscriptions.push(hoverProvider);
}

